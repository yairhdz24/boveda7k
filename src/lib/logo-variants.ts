/** Logos negros sin variante oscura en SVGL: en tema Noche se invierten con CSS. */
const INVERT_ON_DARK = new Set(["expo.svg"]);

export function invertsOnDark(src: string): boolean {
  return src.startsWith(SVGL) && INVERT_ON_DARK.has(src.slice(SVGL.length));
}

/** URL de la variante para fondo oscuro, o null si el logo no tiene. */
export function darkVariant(src: string): string | null {
  if (!src.startsWith(SVGL)) return null;
  const dark = DARK[src.slice(SVGL.length)];
  return dark ? SVGL + dark : null;
}
